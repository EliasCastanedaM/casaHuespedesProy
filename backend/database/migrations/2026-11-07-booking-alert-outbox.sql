-- Cola privada de avisos cuando el cliente acepta una cotización.
-- Solo la conexión PostgreSQL del backend puede leerla/escribirla.
BEGIN;

CREATE TABLE IF NOT EXISTS public.booking_alert_outbox (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  alert_key TEXT NOT NULL UNIQUE,
  channel TEXT NOT NULL CHECK (channel IN ('whatsapp', 'facebook', 'instagram')),
  external_user_id TEXT NOT NULL,
  payload JSONB NOT NULL DEFAULT '{}'::jsonb,
  status TEXT NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'sending', 'failed', 'sent')),
  attempts INTEGER NOT NULL DEFAULT 0,
  next_attempt_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  locked_at TIMESTAMPTZ,
  meta_message_id TEXT,
  last_error TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  sent_at TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS idx_booking_alert_outbox_delivery
  ON public.booking_alert_outbox (next_attempt_at, id)
  WHERE status IN ('pending', 'failed', 'sending');

ALTER TABLE public.booking_alert_outbox ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.booking_alert_outbox FROM PUBLIC, anon, authenticated, service_role;
REVOKE ALL ON SEQUENCE public.booking_alert_outbox_id_seq FROM PUBLIC, anon, authenticated, service_role;

CREATE OR REPLACE FUNCTION public.queue_accepted_reservation_alert()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public, pg_temp
AS $fn$
DECLARE
  prior_state JSONB;
  current_state JSONB;
  previous_quote JSONB;
  current_quote JSONB;
  key_value TEXT;
BEGIN
  prior_state := COALESCE(OLD.booking_context->'whatsapp_mvp', '{}'::jsonb);
  current_state := COALESCE(NEW.booking_context->'whatsapp_mvp', '{}'::jsonb);
  previous_quote := COALESCE(prior_state->'pricing_quote', '{}'::jsonb);
  current_quote := COALESCE(current_state->'pricing_quote', '{}'::jsonb);

  -- Solo la transición cotización vigente -> aceptación con revisión humana.
  -- Otras solicitudes de atención manual jamás disparan un aviso de reserva.
  IF prior_state->>'state' IS DISTINCT FROM 'quoted'
     OR current_state->>'state' IS DISTINCT FROM 'handoff'
     OR current_quote->>'category_slug' IS NULL
     OR COALESCE((current_quote->>'total_amount')::numeric, 0) <= 0
     OR current_state->>'check_in' IS NULL
     OR current_state->>'check_out' IS NULL
     OR previous_quote->>'category_slug' IS DISTINCT FROM current_quote->>'category_slug'
     OR previous_quote->>'total_amount' IS DISTINCT FROM current_quote->>'total_amount'
     OR previous_quote->>'check_in' IS DISTINCT FROM current_quote->>'check_in'
     OR previous_quote->>'check_out' IS DISTINCT FROM current_quote->>'check_out'
  THEN
    RETURN NEW;
  END IF;

  -- La clave depende de la conversación, intención y cotización aceptada.
  -- Un webhook reintentado o una misma transición repetida no se duplica.
  key_value := md5(concat_ws('|', NEW.channel, NEW.external_user_id,
    COALESCE(current_state->>'intent_id', ''),
    current_quote::text));

  INSERT INTO public.booking_alert_outbox
    (alert_key, channel, external_user_id, payload)
  VALUES (
    key_value, NEW.channel, NEW.external_user_id,
    jsonb_build_object(
      'check_in', current_state->>'check_in',
      'check_out', current_state->>'check_out',
      'adults', current_state->'adults',
      'children', current_state->'children',
      'child_ages', current_state->'child_ages',
      'total_guests', current_state->'total_guests',
      'pets', current_state->'pets',
      'customer_name', current_state->>'customer_name',
      'customer_phone', current_state->>'customer_phone',
      'category_name', COALESCE(current_quote->>'category_name',
         current_state->'recommended_category'->>'name',
         current_state->>'category_slug'),
      'preferences', current_state->>'preferences',
      'requested_preferences', current_state->'requested_room_preferences',
      'total_amount', current_quote->'total_amount'
    )
  )
  ON CONFLICT (alert_key) DO NOTHING;

  RETURN NEW;
END
$fn$;

REVOKE ALL ON FUNCTION public.queue_accepted_reservation_alert()
  FROM PUBLIC, anon, authenticated, service_role;

DROP TRIGGER IF EXISTS trg_queue_accepted_reservation_alert
  ON public.ai_conversations;
CREATE TRIGGER trg_queue_accepted_reservation_alert
AFTER UPDATE OF booking_context ON public.ai_conversations
FOR EACH ROW EXECUTE FUNCTION public.queue_accepted_reservation_alert();

COMMIT;
